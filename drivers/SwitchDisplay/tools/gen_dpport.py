# Generates drivers/SwitchDisplay/src/dpalt_port.inc from the UEFI sources
# (R426 DPAUX1, R427 link, R429/R433 DC-B video). Only mechanical changes.
import re, sys
# usage: python gen_dpport.py <Windows-for-Switch>/Drivers/UsbPowerAuditDxe/UsbPowerAudit.c [out.inc]
import os
src = sys.argv[1]
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'dpalt_port.inc')
L = open(src, encoding='ascii', newline='').read().replace('\r\n', '\n').split('\n')


def find(pat, start=0):
    for i in range(start, len(L)):
        if L[i].startswith(pat):
            return i
    raise SystemExit('not found: ' + pat)


a0 = find('// R426: USB-C DisplayPort Alt Mode, stage 2a')
a1 = find('STATIC VOID R426PrintSummary', a0)
b0 = find('// R427: USB-C DisplayPort Alt Mode, stage 2b', a1)
b1 = find('STATIC VOID R427PrintSummary', b0)
c0 = find('// R429: USB-C DisplayPort Alt Mode, stage 3', b1)
c1 = find('STATIC VOID R429PrintSummary', c0)
A = L[a0:a1]
B = L[b0:b1]
C = L[c0:c1]

# R427: drop the R439 PMIC block (UEFI R440 turns LDO8 on at boot) and its call.
r0 = next(i for i, l in enumerate(B) if l.startswith('// R439: SOR1 pad power.'))
r1 = next(i for i, l in enumerate(B) if l.startswith('STATIC VOID R427DpLinkStage2b'))
B = B[:r0] + B[r1:]
B = [l for l in B if l.strip() != 'R439PadPower ();']

# R429: drop R429SetColor/R434ShowUefi (UEFI-only) and the stage-3 tail
# (colour sequence, UEFI mirror, R431 hold); the Windows TV window comes after.
s0 = next(i for i, l in enumerate(C) if l.startswith('STATIC VOID R429SetColor'))
s1 = next(i for i, l in enumerate(C) if l.startswith('STATIC VOID R429DpVideoStage3'))
C = C[:s0] + C[s1:]
t0 = next(i for i, l in enumerate(C) if 'mR429Step = mR429Ok ? L"DONE" : L"NOT-AWAKE";' in l)
C = C[:t0 + 1] + ['}', '']
C = [l for l in C if 'CONST UINT32 Colors[4]' not in l and 'CONST CHAR16 *Names[4]' not in l]

text = '\n'.join(['// GENERATED by gen_dpport.py from Windows-for-Switch UsbPowerAudit.c',
                  '// (UEFI R426/R427/R429/R433, DP Alt Mode). Do not edit by hand.', ''] + A + [''] + B + [''] + C)

subs = [
    ('(volatile UINT32 *)CAR_BASE', '(volatile UINT32 *)gDpCar'),
    ('(volatile UINT32 *)PMC_BASE', '(volatile UINT32 *)gDpPmc'),
    ('((volatile UINT32 *)R426_DPAUX1_BASE)', '((volatile UINT32 *)gDpAux)'),
    ('((volatile UINT32 *)R427_SOR1_BASE)', '((volatile UINT32 *)gDpSor)'),
    ('((volatile UINT32 *)R429_DC_BASE)', '((volatile UINT32 *)gDpDcb)'),
    ('gBS->Stall (', 'DpStall ('),
    ('ZeroMem (', 'RtlZeroMemory ('),
    ('CopyMem (', 'RtlCopyMemory ('),
    ('R424ReadHpd (&Pm, &Cnf, &PccHpd);', 'Pm = 0; Cnf = 0; PccHpd = FALSE;   /* PCC1 GPIO not read in Windows */'),
    ('Print (', 'DpLog ('),
    ('Car[0x140 / 4]', '0u /* 0x140 not read */'),
    ('R429DcWr (R429_DC_BG_COLOR, Colors[0]);', 'R429DcWr (R429_DC_BG_COLOR, 0xFF000000U);   /* black until the TV window is on */'),
]
for o, n in subs:
    text = text.replace(o, n)
for bad in ('CAR_BASE', 'PMC_BASE', 'PINMUX', 'GPIO_', 'gBS', 'R434', 'R435', 'Pcd', 'EFI_'):
    for m in re.finditer(bad, text):
        line = text[:m.start()].count('\n') + 1
        print('WARN', bad, 'line', line, text.split('\n')[line - 1].strip()[:100])
open(dst, 'w', encoding='ascii', newline='').write(text.replace('\n', '\r\n'))
print('lines', text.count('\n'))
